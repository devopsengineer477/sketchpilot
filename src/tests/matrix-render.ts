import { SCENARIOS } from './scenario-map';

/**
 * Renders `docs/test-matrix.md` from the scenario map.
 *
 * Shared by the test (which asserts the committed file still matches) and by
 * `npm run docs:matrix` (which rewrites it), so the two can never disagree. It lives in its
 * own module so the generator script can import it without pulling in Vitest.
 */
export function renderMatrix(): string {
  const rows = SCENARIOS.map((scenario) => {
    const where = scenario.references
      .map((reference) =>
        reference.kind === 'script'
          ? `\`${reference.file}\` (\`${reference.marker}\`)`
          : `\`${reference.file}\` → _${reference.title}_`,
      )
      .join('<br>');
    const note = scenario.note ? `<br><sub>${scenario.note}</sub>` : '';
    return `| ${scenario.id} | ${scenario.requirement} | ${where}${note} |`;
  });
  return [
    '# §14 test matrix',
    '',
    '<!-- Generated by `npm run docs:matrix` from `src/tests/scenario-map.ts`. Do not edit by hand. -->',
    '',
    'Every scenario the specification lists in §14, with the named test that covers it.',
    '`src/tests/test-matrix.test.ts` fails if any reference below stops existing — the table',
    'cannot drift away from the code.',
    '',
    '| # | Requirement | Covered by |',
    '| --- | --- | --- |',
    ...rows,
    '',
  ].join('\n');
}
